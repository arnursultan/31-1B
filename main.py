import sys
from PyQt6.QtWidgets import QApplication
from ui.main_window import MainWindow   # импортируем наше главное окно из отдельного файла
                                        # (вынесено для удобства — декомпозиция проекта)

def main():
    # QApplication — "сердце" любого PyQt-приложения.
    # Оно отвечает за обработку событий: клики, нажатия клавиш, обновления интерфейса и т.д.
    app = QApplication(sys.argv)

    # Устанавливаем имя приложения (может отображаться в заголовках или диспетчере задач).
    app.setApplicationName("PyQt6 проект")

    # Создаём объект нашего главного окна.
    window = MainWindow()

    # Задаём стартовый размер окна (ширина 900 px, высота 600 px).
    window.resize(900, 600)

    # Делаем окно видимым (по умолчанию оно создаётся скрытым).
    window.show()

    # Запускаем главный цикл обработки событий приложения.
    # Пока окно открыто — программа работает. После закрытия — завершается.
    sys.exit(app.exec())

# Эта проверка нужна, чтобы код выполнялся только при прямом запуске файла,
# а не при его импорте как модуля.
if __name__ == '__main__':
    main()
